"""Reproduce the exact shared AFM/CFF metric subset; emit no font program data."""
import argparse,hashlib,re,subprocess
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('source');p.add_argument('oracle');p.add_argument('output');a=p.parse_args();root=Path(a.source)
faces=[('HELVETICA','Helvetica','NimbusSans-Regular','ed4ead49b4d090c80c1d4a8d771879153a41af262d331168dd2635508634cfa1','366720e054067fa49d030f58005c739fc787dcc9727a9327a28767777791d706'),('TIMES_ROMAN','Times-Roman','NimbusRoman-Regular','e476212c416039aa9805f20d945e2b3a522be5de15125cb566d257482379ccd9','eb609a306b81357853ba91c2a3c47f3bba04f3a8cfdeedc733b1aa4af5d03d4c')]
output=['// SPDX-License-Identifier: OFL-1.1','// Generated metric data derived from pinned URW font resources.','// Copyright (URW)++, Copyright 2014 by (URW)++ Design & Development.','// Copyright 2016 URW++ Design & Development.','// Full SIL Open Font License 1.1 and applicable notices: see NOTICE.','// Generated by tools/generate-builtin-metrics.py; do not hand-edit.','// Exact AFM/CFF shared glyph names only; no font programs or Unicode mappings.','']
for symbol,face,file,afm_sha,cff_sha in faces:
 afm_path=f'resources/fonts/urw/input/{file}.afm';cff_path=f'resources/fonts/urw/{file}.cff'
 data=(root/afm_path).read_bytes()
 if hashlib.sha256(data).hexdigest()!=afm_sha or hashlib.sha256((root/cff_path).read_bytes()).hexdigest()!=cff_sha:raise SystemExit('pinned font source mismatch')
 rows={}
 for line in data.decode('ascii').splitlines():
  m=re.match(r'^C -?\d+ ; WX (\d+) ; N ([^ ;]+) ;',line)
  if m:
   value,name=m.groups()
   if name in rows:raise SystemExit('duplicate AFM name')
   rows[name]=int(value)
 if len(rows)!=855:raise SystemExit('unexpected AFM size')
 names=sorted(rows);run=subprocess.run([a.oracle,face],input=('\n'.join(names)+'\n').encode('ascii'),capture_output=True,timeout=10)
 if run.returncode or run.stderr:raise SystemExit('native glyph query failed')
 lines=run.stdout.decode('ascii').splitlines()
 if len(lines)!=len(names):raise SystemExit('native count mismatch')
 shared=[]
 for name,line in zip(names,lines):
  native_name,found,gid,units,raw,integer=line.split('\t')
  if native_name!=name:raise SystemExit('native name mismatch')
  if int(found):
   if int(raw)*1000!=rows[name]*int(units) or int(integer)!=rows[name] or not 0<=rows[name]<=65535:raise SystemExit('width mismatch')
   shared.append((name,rows[name]))
 if len(shared)!=654:raise SystemExit('unexpected shared subset size')
 output.extend([f'// {afm_path} SHA256 {afm_sha}',f'// {cff_path} SHA256 {cff_sha}',f'pub(super) static {symbol}: [(&[u8], u16); 654] = ['])
 for name,value in shared:
  escaped=name.replace('\\','\\\\').replace('"','\\"');output.append(f'    (b"{escaped}", {value}),')
 output.extend(['];',''])
Path(a.output).write_text('\n'.join(output))
print('Generated 1308 verified shared glyph metrics')
