"""Generate pinned OFL bold/oblique outlines; verify the extractor against R20."""
import gzip, hashlib, json, pathlib, subprocess, sys
root = pathlib.Path(__file__).resolve().parents[1]
assets, oracle = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
sha = lambda data: hashlib.sha256(data).hexdigest()
expected = {'Helvetica':'366720e054067fa49d030f58005c739fc787dcc9727a9327a28767777791d706', 'Helvetica-Bold':'d4ea80d1d0e29a1e950808009ca8f96fe07a0670b60b556f6b2cf0705337fa9f', 'Helvetica-BoldOblique':'9cdfc2d0947339dce76f99bdf9e2d9fe01e472a384cf683007e6a0bb35634623'}
fonts={}
for name,digest in expected.items():
    path=assets/(name+'.cff')
    assert sha(path.read_bytes())==digest, name
    run=subprocess.run([str(oracle),str(path)],check=True,capture_output=True,timeout=30)
    rows=json.loads(run.stdout)
    assert len(rows)==654 and len({r['name'] for r in rows})==654
    assert sorted(r['gid'] for r in rows)==list(range(654))
    fonts[name]=sorted(rows,key=lambda r:r['name'])
# Exact regression against all R20 regular-face outline commands and advances.
manifest=json.loads((root/'reference/builtin-outlines-manifest.json').read_text())
regular=next(f for f in manifest['faces'] if f['face']=='Helvetica')
for actual,old in zip(fonts['Helvetica'],regular['records'],strict=True):
    assert actual['name']==old['name'] and actual['gid']==old['native_gid']
    assert actual['advance']==old['advance']
    assert sha(json.dumps(actual['commands'],separators=(',',':')).encode())==old['commands_sha256'],actual['name']
lines=['// SPDX-License-Identifier: OFL-1.1','// Derived from URW NimbusSans pinned CFF assets. Copyright (URW)++, 2014/2016.','// License: reference/licenses/urw-outlines/OFL.txt. See NOTICE.','// Generated by tools/generate-substitute-outlines.py. Do not hand-edit.','use super::{BuiltinFace, BuiltinOutline, BuiltinOutlineCommand};','']
metrics=['// SPDX-License-Identifier: OFL-1.1','// Derived from URW NimbusSans pinned CFF assets. Copyright (URW)++, 2014/2016.','// License: reference/licenses/urw-outlines/OFL.txt. See NOTICE.','// Generated by tools/generate-substitute-outlines.py. Do not hand-edit.','']
evidence=[]
for name,variant,symbol in [('Helvetica-Bold','HelveticaBold','HELVETICA_BOLD'),('Helvetica-BoldOblique','HelveticaBoldOblique','HELVETICA_BOLD_OBLIQUE')]:
    commands=[];records=[]
    for row in fonts[name]:
        assert 0<=row['advance']<=65535
        records.append((row,len(commands)))
        commands.extend(row['commands'])
    assert len(commands)<1000000
    lines += ['#[rustfmt::skip]',f'pub(super) static {symbol}_COMMANDS: [BuiltinOutlineCommand; {len(commands)}] = [']
    for c in commands:
        assert all(isinstance(v,int) and abs(v)<=1000000 for v in c[1:])
        if c[0]=='h': value='Close'
        else:
            kind,keys={'m':('MoveTo',['x','y']),'l':('LineTo',['x','y']),'c':('CubicTo',['x1','y1','x2','y2','x','y'])}[c[0]]
            assert len(c)==len(keys)+1
            value=kind+' { '+', '.join(f'{k}: {v}' for k,v in zip(keys,c[1:]))+' }'
        lines.append('    BuiltinOutlineCommand::'+value+',')
    lines += ['];','#[rustfmt::skip]',f'pub(super) static {symbol}: [BuiltinOutline; 654] = [']
    for r,start in records:
        assert all(33<=ord(c)<=126 and c not in '\\"' for c in r['name'])
        lines.append(f'    BuiltinOutline {{ face: BuiltinFace::{variant}, name: b"{r["name"]}", native_gid: {r["gid"]}, command_start: {start}, command_len: {len(r["commands"])} }},')
    lines += ['];','']
    metrics += ['#[rustfmt::skip]',f'pub(super) static {symbol}: [(&[u8], u16); 654] = [']+[f'    (b"{r["name"]}", {r["advance"]}),' for r in fonts[name]]+['];','']
    evidence.append({'face':name,'sha256':expected[name],'glyphs':654,'commands':len(commands),'extractedSha256':sha(json.dumps(fonts[name],sort_keys=True).encode())})
for name,parts in [('substitute_outlines_data.rs',lines),('substitute_metrics_data.rs',metrics)]:
    data=('\n'.join(parts)+'\n').encode();(root/'src'/name).write_bytes(data)
    evidence.append({'output':name,'sha256':sha(data)})
(assets/'generated-fonts.json').write_text(json.dumps({'regularR20ExactMatch':True,'fonts':evidence},indent=2)+'\n')
print(json.dumps(evidence))
