"""Generate src/view/fonts_unicode.rs: the Unicode scalar of every glyph name
in the engine's URW outline tables, for the cmap of the fonts the view builds
(src/view/fonts.rs). Names resolve through the Adobe Glyph List as pinned
hayro-interpret 0.8.0 embeds it, and uniXXXX / uXXXX[XX] names by their hex.

usage: tools/generate-view-font-unicode.py HAYRO_INTERPRET_SRC_DIR > src/view/fonts_unicode.rs
"""
import hashlib
import pathlib
import re
import sys

engine = pathlib.Path(__file__).resolve().parent.parent
hayro = pathlib.Path(sys.argv[1]) / "font/generated/glyph_names.rs"
source = hayro.read_bytes()
agl = {}
for m in re.finditer(rb'^\s*"([^"]+)" => "((?:\\u\{[0-9A-Fa-f]+\})+)",', source, re.M):
    scalars = [int(x, 16) for x in re.findall(rb"\\u\{([0-9A-Fa-f]+)\}", m.group(2))]
    if len(scalars) == 1:
        agl[m.group(1)] = scalars[0]
names = set()
for table in ("src/builtin_outlines_data.rs", "src/substitute_outlines_data.rs"):
    names.update(re.findall(rb'name: b"([^"]+)"', (engine / table).read_bytes()))
names.discard(b".notdef")
rows = []
for name in sorted(names):
    if name in agl:
        rows.append((name, agl[name]))
    elif re.fullmatch(rb"uni[0-9A-F]{4}", name):
        rows.append((name, int(name[3:], 16)))
    elif re.fullmatch(rb"u[0-9A-F]{4,6}", name):
        rows.append((name, int(name[1:], 16)))
    else:
        sys.exit(f"no Unicode for {name!r}")
print("// SPDX-License-Identifier: AGPL-3.0-or-later")
print("// Generated by tools/generate-view-font-unicode.py; do not edit.")
print("// Glyph names of the URW outline tables with their Unicode scalars, from the")
print("// Adobe Glyph List as hayro-interpret 0.8.0 embeds it (MIT OR Apache-2.0;")
print("// the list is Copyright 2002-2019 Adobe, BSD-3-Clause), uniXXXX by its hex.")
print(f"// glyph_names.rs SHA256 {hashlib.sha256(source).hexdigest()}")
print(f"pub(super) static UNICODE: [(&[u8], u32); {len(rows)}] = [")
for name, scalar in rows:
    print(f'    (b"{name.decode()}", 0x{scalar:04X}),')
print("];")
