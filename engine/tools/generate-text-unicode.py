lines += ['', '/// The Macintosh standard glyph order (TrueType post format 1 and 2).',
          f'pub(super) static MAC_GLYPHS: [&[u8]; {len(MAC)}] = [']
lines += ['    ' + ' '.join(f'b"{n}",' for n in MAC[i:i + 6]) for i in range(0, len(MAC), 6)]
lines.append('];')
# U+FEFF alone on a page reads as nothing, but between other text MuPDF keeps it.
forms = [(c, out) for c, out in sorted(rewritten.items()) if out and out != [FFFD, FFFD]]
lines += ['', '/// Presentation forms and ligatures and the text structured text gives them.',
          f'pub(super) static FORMS: [(u32, &str); {len(forms)}] = [']
lines += [f'    (0x{c:04X}, "{esc(out)}"),' for c, out in forms]
lines.append('];')
# Directions for structured text (measured: MuPDF's stext reads R and AL
# right to left, L, EN, ES and ET left to right, and lets every other class
# take the direction of the character before it).
def bidi_kind(c):
    if 0xD800 <= c <= 0xDFFF:
        return None
    b = unicodedata.bidirectional(chr(c))
    if b in ('R', 'AL'):
        return 1
    if b in ('AN', 'CS', 'NSM', 'BN', 'B', 'S', 'WS', 'ON'):
        return 0
    return None


bidi = []
for c in range(0x110000):
    k = bidi_kind(c)
    if k is not None and bidi and bidi[-1][2] == k and bidi[-1][1] == c - 1:
        bidi[-1][1] = c
    elif k is not None:
        bidi.append([c, c, k])
lines += ['', f'/// Bidirectional classes (Unicode {unicodedata.unidata_version}): 1 for R and AL, 0 for the',
          '/// classes that take the preceding direction; code points not listed are L-like.',
          f'pub(super) static BIDI: [(u32, u32, u8); {len(bidi)}] = [']
lines += [f'    (0x{a:04X}, 0x{b:04X}, {k}),' for a, b, k in bidi]
lines.append('];')
pathlib.Path(out_path).write_text('\n'.join(lines) + '\n')
print(f'{len(names)} names, {len(ucs2)} TrueType-UCS2 CIDs, {len(forms)} forms, {len(bidi)} bidi ranges')
