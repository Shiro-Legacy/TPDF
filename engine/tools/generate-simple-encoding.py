"""Generate the exact S0 subset from verified MuPDF1.28.1 source, never codecs."""
import argparse
import hashlib
import pathlib
import re
import subprocess

p = argparse.ArgumentParser()
p.add_argument('source', type=pathlib.Path)
p.add_argument('output', type=pathlib.Path)
a = p.parse_args()
expected = {
 'source/fitz/encodings.h':'224122c5581a91254a22d3a009c50322d39fbbac5f1b2c1c5464cba8528839de',
 'source/fitz/glyphlist.h':'16fe0427189e16ff852c02984a49dba184c0db51756b8ecef01524ad6efb6002',
 'source/fitz/encodings.c':'db046231a23e4470c89e31850cff8670a1ca95def64c71d0d4f4c416622fe4a6',
}
contents = {}
for path, checksum in expected.items():
    raw = (a.source/path).read_bytes()
    if hashlib.sha256(raw).hexdigest() != checksum:
        raise ValueError(f'pinned source mismatch: {path}')
    contents[path] = raw.decode('ascii')

def array(text, name):
    return re.search(r'\b'+name+r'\[[^]]*\]\s*=\s*\{(.*?)\};',text,re.S).group(1)

names = re.findall(r'"([^"]+)"',array(contents['source/fitz/glyphlist.h'],'single_name_list'))
codes = [int(v,16) for v in re.findall(r'0x([0-9a-fA-F]+)',array(contents['source/fitz/glyphlist.h'],'single_code_list'))]
assert len(names)==len(codes)==len(set(names))
registry=dict(zip(names,codes))
lines=['// SPDX-License-Identifier: AGPL-3.0-or-later',
 '// Generated by tools/generate-simple-encoding.py; do not edit.',
 '// Derived from MuPDF 1.28.1, Copyright (C) 2004-2021 Artifex Software, Inc.',
 '// This exact 378-name subset is not a general Adobe Glyph List resolver.',
 '// Relevant source SHA256 values:']
lines.extend('// '+path+' '+checksum for path,checksum in expected.items())
used=set()
for rust,source in [('WIN_ANSI','win_ansi'),('MAC_ROMAN','mac_roman'),('STANDARD','adobe_standard'),('MAC_EXPERT','mac_expert')]:
    values=[name if name else None for name,undefined in re.findall(r'"([^"]+)"|(_notdef)',array(contents['source/fitz/encodings.h'],'fz_glyph_name_from_'+source))]
    assert len(values)==256
    lines.append('pub(super) const '+rust+': [Option<&[u8]>; 256] = [')
    for name in values:
        if name:
            assert re.fullmatch(r'[a-zA-Z0-9_.]+',name)
            used.add(name);lines.append('Some(b"'+name+'"),')
        else: lines.append('None,')
    lines.append('];')
assert len(used)==378
lines.append('pub(super) const UNICODE: &[(&[u8], &[char])] = &[')
for name in sorted(used):
    code=registry[name]
    assert 0<code<=0x10ffff and not 0xd800<=code<=0xdfff
    lines.append('(b"'+name+'", &[\'\\u{'+format(code,'x')+'}\']),')
lines.append('];')
a.output.write_text('\n'.join(lines)+'\n')
subprocess.run([str(pathlib.Path.home()/'.cargo/bin/rustfmt'),'--edition','2024',str(a.output)],check=True)
print(f'generated 1024 table slots and {len(used)} exact glyph mappings')
