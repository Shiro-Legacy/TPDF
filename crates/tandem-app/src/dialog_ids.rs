/// The ids inside a dialog or panel, if it is one.
pub fn group(id: &str) -> Option<&'static [(&'static str, &'static str)]> {
    DIALOGS
        .iter()
        .chain(PANELS.iter())
        .find(|(g, _)| *g == id)
        .map(|(_, ids)| *ids)
}
